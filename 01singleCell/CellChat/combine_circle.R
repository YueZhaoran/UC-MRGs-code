library(png)
library(grid)
combine <- function(f1, f2, out) {
  a <- readPNG(f1)
  b <- readPNG(f2)
  png(out, width = 7000, height = 4500, res = 600)
  grid.newpage()
  pushViewport(viewport(layout = grid.layout(1, 2)))
  pushViewport(viewport(layout.pos.col = 1))
  grid.raster(a)
  popViewport()
  pushViewport(viewport(layout.pos.col = 2))
  grid.raster(b)
  popViewport()
  dev.off()
  cat(out, "done\n")
}
combine("circle_number_HC.png", "circle_number_UC.png", "circle_number_compare.png")
combine("circle_weight_HC.png", "circle_weight_UC.png", "circle_weight_compare.png")
